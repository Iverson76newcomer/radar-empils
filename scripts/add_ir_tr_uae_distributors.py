# === Открываем файл и добавляем данные ===

wb = load_workbook(DST)
ws = wb["Лист1"]

# Определяем последнюю заполненную строку
last_row = ws.max_row
# Найдём реальную последнюю строку с данными в колонке A
for row_idx in range(ws.max_row, 0, -1):
    if ws.cell(row=row_idx, column=1).value is not None:
        last_row = row_idx
        break

print(f"Исходное количество строк с данными: {last_row - 3}")  # -3 потому что заголовок на R3

# Стиль для новых строк — такой же как в существующих
thin_border = Border(
    top=Side(style="thin", color="DDD0C8"),
    bottom=Side(style="thin", color="DDD0C8"),
    left=Side(style="thin", color="DDD0C8"),
    right=Side(style="thin", color="DDD0C8"),
)

# Цвет фона для новых стран
COUNTRY_COLORS = {
    "Иран":   "E8F5E9",  # светло-зелёный
    "Турция": "E3F2FD",  # светло-голубой
    "ОАЭ":    "FFF3E0",  # светло-оранжевый
}

# Добавляем новые строки после последней заполненной
start_row = last_row + 1

for i, row_data in enumerate(NEW_DATA):
    row_num = start_row + i
    country = row_data[0]

    for col_idx, value in enumerate(row_data, 1):
        cell = ws.cell(row=row_num, column=col_idx, value=value)
        cell.font = Font(name="Calibri", size=10, color="313131",
                         bold=(col_idx == 3))  # Компания — жирная
        cell.alignment = Alignment(
            horizontal="center" if col_idx in (1, 2) else "left",
            vertical="center",
            wrap_text=True
        )
        cell.border = thin_border

        # Цвет строки по стране
        if country in COUNTRY_COLORS:
            cell.fill = PatternFill("solid", fgColor=COUNTRY_COLORS[country])

    ws.row_dimensions[row_num].height = 65

# Сохраняем
wb.save(DST)

total_added = len(NEW_DATA)
print(f"\n✅ Файл обновлён: {DST}")
print(f"   Размер: {os.path.getsize(DST):,} байт")
print(f"   Добавлено компаний: {total_added}")
print(f"   Из Ирана: 8")
print(f"   Из Турции: 8")
print(f"   Из ОАЭ: 8")
print(f"   Всего строк в файле: {start_row + total_added - 4}")
