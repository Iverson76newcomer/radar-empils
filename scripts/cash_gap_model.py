"""
Модель кассового разрыва для дистрибьютора Олимп.
Исходные данные:
- Год 1: товарооборот 60 млн руб
- 300 SKU, есть стоимость каждой позиции
- Условия оплаты: 45 дней постоплата (дистрибьютор платит Эмпилс через 45 дней после отгрузки)
- Наценка дистрибьютора 35% (базовая)
- С января по май закупается 50% от годового плана = 30 млн руб первички
- Январь: фиксированная первичка (по экспертной оценке - это стартовая закупка)
- С июня по декабрь: 30 млн руб распределяется по убывающей (пик сезона пройден)
- Вторичка (продажи в РТТ):
  - январь: 2 млн руб
  - февраль: 2,4 млн руб
  - март: 4,8 млн руб
  - апрель: 7,8 млн руб
  - май: 7,8 млн руб
  - далее нужно продолжить до 60 млн руб годовой
"""

import openpyxl
from openpyxl import load_workbook
import json

# === 1. Загрузить ассортимент v4 и получить себестоимость ===
wb = load_workbook("/home/z/my-project/upload/Ассортимент_Олимп_300_SKU_финал_v4.xlsx", data_only=True)
ws = wb["300 SKU с ценами"]

# Считать данные: idx, name, отгрузочная цена, базовая цена
sku_list = []
total_cost = 0
for r in range(5, ws.max_row + 1):
    idx = ws.cell(row=r, column=1).value
    if idx is None:
        continue
    name = ws.cell(row=r, column=7).value
    otn_price = ws.cell(row=r, column=10).value  # отгрузочная цена (для Олимпа = себестоимость покупки)
    base_price = ws.cell(row=r, column=11).value
    fasovka = ws.cell(row=r, column=12).value
    
    if otn_price and isinstance(otn_price, (int, float)):
        sku_list.append({
            'idx': idx, 'name': name, 'cost': otn_price, 'base_price': base_price, 'fasovka': fasovka
        })
        total_cost += otn_price

print(f"=== Ассортимент v4 ===")
print(f"Всего SKU с ценой: {len(sku_list)}")
print(f"Сумма отгрузочных цен всех 300 SKU: {total_cost:.0f} руб")
print(f"Средняя отгрузочная цена 1 SKU: {total_cost/len(sku_list):.0f} руб")

# Сортировка по цене для понимания структуры
sku_sorted = sorted(sku_list, key=lambda x: -x['cost'])
print(f"\n=== Топ-10 самых дорогих SKU ===")
for s in sku_sorted[:10]:
    print(f"  #{s['idx']}: {s['name'][:55]} | {s['cost']:.0f} руб | фас={s['fasovka']}")

print(f"\n=== Топ-10 самых дешёвых SKU ===")
for s in sku_sorted[-10:]:
    print(f"  #{s['idx']}: {s['name'][:55]} | {s['cost']:.0f} руб | фас={s['fasovka']}")

# === 2. Параметры модели ===
print("\n" + "="*80)
print("ПАРАМЕТРЫ МОДЕЛИ")
print("="*80)

ANNUAL_TO = 60_000_000  # 60 млн руб - товарооборот год 1
PRIMARY_TOTAL = 30_000_000  # 30 млн руб - первичка с янв по май (50% от плана)
DEFERRED_PAYMENT_DAYS = 45  # постоплата 45 дней
MARKUP_DISTRIBUTOR = 0.35  # наценка 35% (дистр→РТТ)
# Т.е. дистрибьютор покупает за X, продаёт за X×1.35

print(f"Товарооборот год 1: {ANNUAL_TO:,} руб")
print(f"Первичка (50% от плана, янв-май): {PRIMARY_TOTAL:,} руб")
print(f"Условия оплаты: постоплата {DEFERRED_PAYMENT_DAYS} дней")
print(f"Наценка дистрибьютора: {MARKUP_DISTRIBUTOR*100}%")

# === 3. Распределение первички по месяцам ===
# Экспертная оценка: с января по май закупается 30 млн
# Из данных интернета: пик спроса - июнь (+25% к весне), строительный сезон - апрель-сентябрь
# Значит, первичка идёт В ОПЕРЕЖЕНИЕ вторички (нужно сначала закупить, потом продать)
# Логика: январь - стартовая закупка (15-20% от первички), 
#         февраль-май - нарастание к пику сезона (июнь-июль)

# По экспертной оценке: январь - примерно 1/5 от 30 млн = ~6 млн (стартовая)
# Это согласуется с КП: 4 ЭТП × 120 РТТ = на старте нужно загрузить склад

# Распределение янв-май (30 млн всего):
# Экспертно: январь - 5-6 млн (старт склада)
#             февраль - 5-6 млн (подгрузка перед мартом)
#             март - 7-8 млн (пик подготовки к апрель-май)
#             апрель - 6-7 млн (поддержание наличия)
#             май - 4-5 млн (пополнение перед июньским пиком)

# Однако, более точно по сезону ЛКМ:
# Январь - низкий сезон (ремонт квартир)
# Февраль - начало подготовки
# Март - первая волна (майские праздники впереди)
# Апрель - пик весенней загрузки
# Май - поддержание
# По данным источников: "пик продаж - июнь, спрос +25% к весне"
# Значит, нужно заранее загрузить склад в апреле-мае, чтобы встретить июньский пик

# Экспертное распределение (с учётом сезонности):
primary_plan_jan_may = {
    'Январь': 6_000_000,   # стартовая загрузка склада (10% годовой первички)
    'Февраль': 6_000_000,  # продолжение формирования склада (10%)
    'Март': 7_000_000,     # первая волна под майские (11.7%)
    'Апрель': 7_000_000,   # пик весенней закупки (11.7%)
    'Май': 4_000_000,      # поддержание склада (6.7%)
}
# Сумма янв-май = 6+6+7+7+4 = 30 млн ✓

# С июня по декабрь нужно распределить оставшиеся 30 млн (60 - 30 = 30 млн) по убывающей
# Убывающая кривая: июнь - пик (поддержание продаж), далее спад
# Пропорции по убывающей (всего 100% на 7 месяцев):
# июнь - 22%, июль - 20%, август - 17%, сентябрь - 14%, октябрь - 11%, ноябрь - 9%, декабрь - 7%

primary_plan_jun_dec = {
    'Июнь': 6_600_000,    # 22% от 30 млн - пик сезона
    'Июль': 6_000_000,    # 20%
    'Август': 5_100_000,  # 17%
    'Сентябрь': 4_200_000, # 14%
    'Октябрь': 3_300_000,  # 11%
    'Ноябрь': 2_700_000,   # 9%
    'Декабрь': 2_100_000,  # 7%
}
# Сумма июн-дек = 6.6+6.0+5.1+4.2+3.3+2.7+2.1 = 30 млн ✓

# Полный план первички
primary_plan = {**primary_plan_jan_may, **primary_plan_jun_dec}

print(f"\n=== План первички по месяцам ===")
total_check = 0
for m, v in primary_plan.items():
    print(f"  {m}: {v:,} руб ({v/ANNUAL_TO*100:.1f}% от ТО)")
    total_check += v
print(f"  ИТОГО: {total_check:,} руб (должно быть 60 млн)")

# === 4. План вторички (продажи в РТТ) ===
# По экспертной оценке:
#   январь: 2 млн, февраль: 2,4 млн, март: 4,8 млн, апрель: 7,8 млн, май: 7,8 млн
# Сумма янв-май = 2+2,4+4,8+7,8+7,8 = 24,8 млн (41,3% годового ТО)

# С июня по декабрь нужно 60 - 24,8 = 35,2 млн распределить
# Пик продаж - июнь (+25% к весне), затем спад к зиме
# Пропорции (июнь-дек, всего 100%):
# июнь - 22%, июль - 22%, август - 18%, сентябрь - 13%, октябрь - 10%, ноябрь - 8%, декабрь - 7%

secondary_plan = {
    'Январь': 2_000_000,    # 3,3% годового ТО (старт, низкий сезон)
    'Февраль': 2_400_000,   # 4,0%
    'Март': 4_800_000,      # 8,0% (первая волна перед майскими)
    'Апрель': 7_800_000,    # 13,0% (пик весенней загрузки)
    'Май': 7_800_000,       # 13,0% (пик весенней загрузки)
    'Июнь': 7_750_000,      # 22% от 35,2 млн = пик сезона
    'Июль': 7_750_000,      # 22%
    'Август': 6_340_000,    # 18%
    'Сентябрь': 4_580_000,  # 13%
    'Октябрь': 3_520_000,   # 10%
    'Ноябрь': 2_820_000,    # 8%
    'Декабрь': 2_460_000,   # 7%
}

print(f"\n=== План вторички (продажи в РТТ) по месяцам ===")
total_check = 0
for m, v in secondary_plan.items():
    print(f"  {m}: {v:,} руб ({v/ANNUAL_TO*100:.1f}% от ТО)")
    total_check += v
print(f"  ИТОГО: {total_check:,} руб (должно быть 60 млн)")

# === 5. Кассовый поток с учётом отсрочки 45 дней ===
# Дистрибьютор покупает у Эмпилс с постоплатой 45 дней
# Это значит: в месяце N получает товар, в месяце N+1.5 (середина следующего+1) платит
# Расчёт: 45 дней ≈ 1,5 месяца
# Условно: если закупка в январе, оплата в середине марта
# Если в феврале - в середине апреля и т.д.

# Также дистрибьютор продаёт в РТТ (тоже с отсрочкой? или предоплата?)
# Обычно РТТ платят дистрибьютору с отсрочкой 14-30 дней
# В КП не указано, какая именно отсрочка от РТТ
# Будем считать: РТТ платит через 30 дней после отгрузки

# Кассовый поток:
# - Поступления от РТТ (через 30 дней после вторички)
# - Платежи Эмпилс (через 45 дней после первички)

# Предположим: начало месяца 1 января
# Январь: первичка 1 января (долг Эмпилс до 15 февраля)
#         вторичка 15 января (деньги от РТТ 14 февраля)

# Простой поток:
# В каждом месяце фиксируем:
# 1. Поступление первички (товар получен, но не оплачен)
# 2. Отгрузка вторички в РТТ (товар ушёл, но деньги ещё не пришли)
# 3. Оплата Эмпилсу (через 45 дней после первички)
# 4. Поступление денег от РТТ (через 30 дней после вторички)

# Упростим: рассмотрим 12 месяцев денежного потока
# При 45-дневной отсрочке: если первичка идёт в месяце N (равномерно весь месяц),
# то средняя дата оплаты = N + 1.5 месяца
# То есть январская первичка оплачивается во второй половине февраля - первой марта
# Условно: 50% в феврале, 50% в марте

# При 30-дневной отсрочке от РТТ: январская вторичка приносит деньги в феврале

print("\n" + "="*80)
print("КАССОВЫЙ ПОТОК (по месяцам)")
print("="*80)

months = ['Январь', 'Февраль', 'Март', 'Апрель', 'Май', 'Июнь', 
          'Июль', 'Август', 'Сентябрь', 'Октябрь', 'Ноябрь', 'Декабрь']

# Для расчёта кассового разрыва:
# - ВХОД: деньги от РТТ (с лагом 30 дней = +1 месяц)
#         + стартовый капитал дистрибьютора (предположим X руб)
# - ВЫХОД: оплата Эмпилс (с лагом 45 дней)
#          + операционные расходы (зарплата, склад, логистика) — упрощаем, без них

# Упрощённая модель (45 дней ≈ 1.5 месяца):
# Платежи Эмпилс в месяце N = 50% × первичка[N-2] + 50% × первичка[N-1]
# Это значит, оплата за январь делится: 50% в феврале, 50% в марте

# Поступления от РТТ (30 дней = +1 месяц):
# Поступления в месяце N = 100% × вторичка[N-1]

cash_flow = []
cumulative_balance = 0  # стартуем с 0 (или с каким-то капиталом)

# Будем считать, что у дистрибьютора есть стартовый капитал.
# Кассовый разрыв = момент, когда кумулятивный баланс становится отрицательным

# Уточнение: 45 дней ≈ 1.5 месяца. Если первичка распределена равномерно в течение месяца,
# средняя дата получения = середина месяца. Тогда оплата = середина + 45 дней = середина месяца + 1.5 мес
# То есть: январская первичка (средняя дата 15 янв) → оплата ~1 марта
# Условно: 100% первички месяца N оплачивается в месяце N+2 (для простоты)
# Аналогично: 100% вторички месяца N приносит деньги в месяце N+1 (30 дней)

# Это упрощение, но оно позволяет увидеть картину

print(f"\n{'Месяц':<10} {'Первичка':>14} {'Вторичка':>14} {'Платёж Эмпилс (T+45)':>22} {'Деньги от РТТ (T+30)':>22} {'Чистый поток':>16} {'Накопл.':>14}")
print("-" * 130)

# Для расчёта с лагами используем предыдущие месяцы
prev_primary = [0, 0]  # [N-2, N-1] для платежей Эмпилс
prev_secondary = [0]   # [N-1] для денег от РТТ

for i, m in enumerate(months):
    prim = primary_plan[m]
    sec = secondary_plan[m]
    
    # Платёж Эмпилс (за первичку 2 месяца назад)
    pay_empils = prev_primary[0]  # это N-2
    
    # Деньги от РТТ (за вторичку 1 месяц назад)
    receive_rtt = prev_secondary[0]  # это N-1
    
    # Чистый поток месяца
    net = receive_rtt - pay_empils
    
    # Накопленный баланс
    cumulative_balance += net
    
    print(f"{m:<10} {prim:>14,} {sec:>14,} {pay_empils:>22,} {receive_rtt:>22,} {net:>16,} {cumulative_balance:>14,}")
    
    cash_flow.append({
        'month': m, 'primary': prim, 'secondary': sec,
        'pay_empils': pay_empils, 'receive_rtt': receive_rtt,
        'net': net, 'cumulative': cumulative_balance,
    })
    
    # Обновляем предыдущие значения
    prev_primary = [prev_primary[1], prim]
    prev_secondary = [sec]

# === 6. Анализ кассового разрыва ===
print("\n" + "="*80)
print("АНАЛИЗ КАССОВОГО РАЗРЫВА")
print("="*80)

min_balance = min(cf['cumulative'] for cf in cash_flow)
min_month = next(cf['month'] for cf in cash_flow if cf['cumulative'] == min_balance)

print(f"\nМинимальный накопленный баланс: {min_balance:,} руб в {min_month}")
print(f"\nКассовый разрыв возникает в первый месяц, где кумулятивный баланс становится отрицательным.")

# Найти первый месяц с отрицательным балансом
first_negative = None
for cf in cash_flow:
    if cf['cumulative'] < 0:
        first_negative = cf
        break

if first_negative:
    print(f"\n✗ КАССОВЫЙ РАЗРЫВ: {first_negative['month']}, баланс = {first_negative['cumulative']:,} руб")
    print(f"  Первичка в этом месяце: {first_negative['primary']:,} руб")
    print(f"  Вторичка в этом месяце: {first_negative['secondary']:,} руб")
    print(f"  Платёж Эмпилс (за 45 дн до этого): {first_negative['pay_empils']:,} руб")
    print(f"  Поступления от РТТ (за 30 дн до этого): {first_negative['receive_rtt']:,} руб")
else:
    print(f"\n✓ Кассовый разрыв НЕ возникает при заданных параметрах")

# Сохраним модель в JSON для генерации Excel
with open('/home/z/my-project/scripts/cash_gap_model.json', 'w', encoding='utf-8') as f:
    json.dump({
        'params': {
            'annual_to': ANNUAL_TO,
            'primary_total': PRIMARY_TOTAL,
            'deferred_payment_days': DEFERRED_PAYMENT_DAYS,
            'markup_distributor': MARKUP_DISTRIBUTOR,
            'rtt_deferred_days': 30,
        },
        'primary_plan': primary_plan,
        'secondary_plan': secondary_plan,
        'cash_flow': cash_flow,
        'min_balance': min_balance,
        'min_month': min_month,
        'first_negative_month': first_negative,
    }, f, ensure_ascii=False, indent=2, default=str)

print(f"\nМодель сохранена в cash_gap_model.json")
