function h1(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_1,
    spacing: { before: 400, after: 200 },
    children: [new TextRun({ text, bold: true, size: 32, color: c(P.primary), font: { ascii: "Calibri", eastAsia: "SimHei" } })]
  });
}

function h2(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_2,
    spacing: { before: 300, after: 150 },
    children: [new TextRun({ text, bold: true, size: 28, color: c(P.primary), font: { ascii: "Calibri", eastAsia: "SimHei" } })]
  });
}

function h3(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_3,
    spacing: { before: 200, after: 100 },
    children: [new TextRun({ text, bold: true, size: 24, color: c(P.accent), font: { ascii: "Calibri", eastAsia: "SimHei" } })]
  });
}

function body(text, indent = true) {
  return new Paragraph({
    alignment: AlignmentType.LEFT,
    indent: indent ? { firstLine: 0 } : undefined,
    spacing: { after: 120, line: 312 },
    children: [new TextRun({ text, size: 22, color: c(P.body), font: { ascii: "Calibri", eastAsia: "Microsoft YaHei" } })]
  });
}

function bold(text) {
  return new TextRun({ text, bold: true, size: 22, color: c(P.body), font: { ascii: "Calibri", eastAsia: "Microsoft YaHei" } });
}

function normal(text) {
  return new TextRun({ text, size: 22, color: c(P.body), font: { ascii: "Calibri", eastAsia: "Microsoft YaHei" } });
}

function accentText(text) {
  return new TextRun({ text, bold: true, size: 22, color: c(P.accent), font: { ascii: "Calibri", eastAsia: "Microsoft YaHei" } });
}

function bodyWithRuns(runs) {
  return new Paragraph({
    alignment: AlignmentType.LEFT,
    spacing: { after: 120, line: 312 },
    children: runs
  });
}

function bulletItem(text, level = 0) {
  return new Paragraph({
    alignment: AlignmentType.LEFT,
    indent: { left: 360 + level * 360 },
    spacing: { after: 60, line: 312 },
    children: [new TextRun({ text: `\u2022 ${text}`, size: 22, color: c(P.body), font: { ascii: "Calibri", eastAsia: "Microsoft YaHei" } })]
  });
}

function numberedItem(num, text) {
  return new Paragraph({
    alignment: AlignmentType.LEFT,
    indent: { left: 360 },
    spacing: { after: 60, line: 312 },
    children: [
      new TextRun({ text: `${num}. `, bold: true, size: 22, color: c(P.accent), font: { ascii: "Calibri", eastAsia: "Microsoft YaHei" } }),
      new TextRun({ text, size: 22, color: c(P.body), font: { ascii: "Calibri", eastAsia: "Microsoft YaHei" } })
    ]
  });
}

function questionCard(qNum, questionText, typeLabel, options, note) {
  const items = [];
  items.push(new Paragraph({
    spacing: { before: 200, after: 80 },
    shading: { type: ShadingType.CLEAR, fill: c(P.surface) },
    indent: { left: 0, right: 0 },
    children: [
      new TextRun({ text: `\u0412\u043E\u043F\u0440\u043E\u0441 ${qNum}. `, bold: true, size: 23, color: c(P.accent), font: { ascii: "Calibri", eastAsia: "Microsoft YaHei" } }),
      new TextRun({ text: questionText, size: 23, color: c(P.primary), font: { ascii: "Calibri", eastAsia: "Microsoft YaHei" } })
    ]
  }));

  items.push(new Paragraph({
    spacing: { after: 80 },
    children: [
      new TextRun({ text: `\u0422\u0438\u043F \u0432 \u042F\u043D\u0434\u0435\u043A\u0441.\u0424\u043E\u0440\u043C\u0430\u0445: `, bold: true, size: 20, color: c(P.secondary), font: { ascii: "Calibri", eastAsia: "Microsoft YaHei" } }),
      new TextRun({ text: typeLabel, size: 20, color: c(P.accent), font: { ascii: "Calibri", eastAsia: "Microsoft YaHei" } })
    ]
  }));

  if (options) {
    for (const opt of options) {
      items.push(new Paragraph({
        indent: { left: 360 },
        spacing: { after: 40, line: 312 },
        children: [new TextRun({ text: `\u25CB  ${opt}`, size: 21, color: c(P.body), font: { ascii: "Calibri", eastAsia: "Microsoft YaHei" } })]
      }));
    }
  }

  if (note) {
    items.push(new Paragraph({
      spacing: { before: 60, after: 120 },
      indent: { left: 360 },
      children: [
        new TextRun({ text: `\u2139\uFE0F `, size: 20, color: c(P.secondary), font: { ascii: "Calibri", eastAsia: "Microsoft YaHei" } }),
        new TextRun({ text: note, italics: true, size: 20, color: c(P.secondary), font: { ascii: "Calibri", eastAsia: "Microsoft YaHei" } })
      ]
    }));
  }

  items.push(new Paragraph({
    spacing: { after: 60 },
    children: [new TextRun({ text: "", size: 8 })]
  }));

  return items;
}

