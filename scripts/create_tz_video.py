def set_cell_shading(cell, hex_color):
    """Заливка ячейки таблицы."""
    tc_pr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement('w:shd')
    shd.set(qn('w:val'), 'clear')
    shd.set(qn('w:color'), 'auto')
    shd.set(qn('w:fill'), hex_color)
    tc_pr.append(shd)


def set_cell_borders(cell, color='D1D5DB', sz='4'):
    """Тонкие серые границы ячейки."""
    tc_pr = cell._tc.get_or_add_tcPr()
    tc_borders = OxmlElement('w:tcBorders')
    for edge in ('top', 'left', 'bottom', 'right'):
        b = OxmlElement(f'w:{edge}')
        b.set(qn('w:val'), 'single')
        b.set(qn('w:sz'), sz)
        b.set(qn('w:color'), color)
        tc_borders.append(b)
    tc_pr.append(tc_borders)


def add_para(doc, text='', size=11, bold=False, color=COL_BODY, align=None,
             font=FONT_BODY, space_before=0, space_after=4, line_spacing=1.3,
             indent_left=0, indent_first=0):
    p = doc.add_paragraph()
    pf = p.paragraph_format
    if align is not None:
        p.alignment = align
    pf.space_before = Pt(space_before)
    pf.space_after = Pt(space_after)
    pf.line_spacing = line_spacing
    if indent_left:
        pf.left_indent = Cm(indent_left)
    if indent_first:
        pf.first_line_indent = Cm(indent_first)
    if text:
        run = p.add_run(text)
        run.font.name = font
        run.font.size = Pt(size)
        run.font.bold = bold
        run.font.color.rgb = color
        # Установить шрифт для кириллицы и латиницы
        rPr = run._element.get_or_add_rPr()
        rFonts = rPr.find(qn('w:rFonts'))
        if rFonts is None:
            rFonts = OxmlElement('w:rFonts')
            rPr.append(rFonts)
        rFonts.set(qn('w:ascii'), font)
        rFonts.set(qn('w:hAnsi'), font)
        rFonts.set(qn('w:cs'), font)
    return p


def add_heading(doc, text, level=1):
    """Заголовок раздела с цветом."""
    if level == 1:
        size, color, sb, sa = 18, COL_PRIMARY, 18, 10
    elif level == 2:
        size, color, sb, sa = 14, COL_PRIMARY, 14, 6
    else:
        size, color, sb, sa = 12, COL_ACCENT, 8, 4
    p = add_para(doc, text, size=size, bold=True, color=color,
                 align=WD_ALIGN_PARAGRAPH.LEFT, space_before=sb, space_after=sa)
    return p


def add_bullet(doc, text, level=0, size=11, bold=False, color=COL_BODY):
    """Маркированный пункт списка."""
    p = doc.add_paragraph(style='List Bullet')
    pf = p.paragraph_format
    pf.left_indent = Cm(1.0 + level * 0.7)
    pf.space_before = Pt(0)
    pf.space_after = Pt(2)
    pf.line_spacing = 1.3
    run = p.add_run(text)
    run.font.name = FONT_BODY
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.color.rgb = color
    rPr = run._element.get_or_add_rPr()
    rFonts = rPr.find(qn('w:rFonts'))
    if rFonts is None:
        rFonts = OxmlElement('w:rFonts')
        rPr.append(rFonts)
    rFonts.set(qn('w:ascii'), FONT_BODY)
    rFonts.set(qn('w:hAnsi'), FONT_BODY)
    rFonts.set(qn('w:cs'), FONT_BODY)
    return p


def add_field_table(doc, rows):
    """Таблица с полями ролика (Цель / Аудитория / Формат / Размещение).
    rows = [(label, value), ...]"""
    table = doc.add_table(rows=len(rows), cols=2)
    table.alignment = WD_TABLE_ALIGNMENT.LEFT
    table.autofit = False
    table.columns[0].width = Cm(4.0)
    table.columns[1].width = Cm(12.5)
    for i, (label, value) in enumerate(rows):
        c1 = table.cell(i, 0)
        c2 = table.cell(i, 1)
        c1.width = Cm(4.0)
        c2.width = Cm(12.5)
        # Заливка
        set_cell_shading(c1, COL_LIGHT_BG)
        # Границы
        set_cell_borders(c1)
        set_cell_borders(c2)
        # Левая ячейка — ярлык
        c1.vertical_alignment = WD_ALIGN_VERTICAL.TOP
        p1 = c1.paragraphs[0]
        p1.paragraph_format.space_before = Pt(4)
        p1.paragraph_format.space_after = Pt(4)
        p1.paragraph_format.line_spacing = 1.3
        r1 = p1.add_run(label)
        r1.font.name = FONT_BODY
        r1.font.size = Pt(10)
        r1.font.bold = True
        r1.font.color.rgb = COL_PRIMARY
        # Правая ячейка — значение
        c2.vertical_alignment = WD_ALIGN_VERTICAL.TOP
        p2 = c2.paragraphs[0]
        p2.paragraph_format.space_before = Pt(4)
        p2.paragraph_format.space_after = Pt(4)
        p2.paragraph_format.line_spacing = 1.3
        r2 = p2.add_run(value)
        r2.font.name = FONT_BODY
        r2.font.size = Pt(10)
        r2.font.color.rgb = COL_BODY
    # Небольшой отступ после таблицы
    add_para(doc, '', size=4, space_after=2)


def add_timing_table(doc, rows):
    """Таблица тайминга: Хронометраж | Сцена | Текст/Действие."""
    headers = ['Хронометраж', 'Сцена / план', 'Текст на экране / действие']
    table = doc.add_table(rows=len(rows) + 1, cols=3)
    table.alignment = WD_TABLE_ALIGNMENT.LEFT
    table.autofit = False
    widths = [Cm(3.0), Cm(6.5), Cm(7.0)]
    for i, w in enumerate(widths):
        table.columns[i].width = w
    # Шапка
    for i, h in enumerate(headers):
        cell = table.cell(0, i)
        cell.width = widths[i]
        set_cell_shading(cell, COL_HEADER_BG)
        set_cell_borders(cell, color='1E3A5F', sz='6')
        cell.vertical_alignment = WD_ALIGN_VERTICAL.CENTER
        p = cell.paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.space_before = Pt(4)
        p.paragraph_format.space_after = Pt(4)
        r = p.add_run(h)
        r.font.name = FONT_BODY
        r.font.size = Pt(10)
        r.font.bold = True
        r.font.color.rgb = RGBColor(0xFF, 0xFF, 0xFF)
    # Данные
    for ri, (time, scene, text) in enumerate(rows, 1):
        bg = 'FFFFFF' if ri % 2 == 1 else 'F9FAFB'
        for ci, val in enumerate([time, scene, text]):
            cell = table.cell(ri, ci)
            cell.width = widths[ci]
            set_cell_shading(cell, bg)
            set_cell_borders(cell)
            cell.vertical_alignment = WD_ALIGN_VERTICAL.TOP
            p = cell.paragraphs[0]
            p.paragraph_format.space_before = Pt(3)
            p.paragraph_format.space_after = Pt(3)
            p.paragraph_format.line_spacing = 1.3
            if ci == 0:
                p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            r = p.add_run(val)
            r.font.name = FONT_BODY
            r.font.size = Pt(9)
            r.font.bold = (ci == 0)
            r.font.color.rgb = COL_PRIMARY if ci == 0 else COL_BODY
    add_para(doc, '', size=4, space_after=2)


