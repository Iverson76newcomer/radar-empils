def make_table(headers, rows, col_widths=None):
    table = doc.add_table(rows=1, cols=len(headers))
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    hdr = table.rows[0].cells
    for i, h in enumerate(headers):
        hdr[i].text = ''
        p = hdr[i].paragraphs[0]; p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        run = p.add_run(h)
        run.font.bold = True; run.font.size = Pt(9); run.font.color.rgb = COLOR_WHITE; run.font.name = 'Arial'
        shade_cell(hdr[i], '009FE3')
    for ri, row_data in enumerate(rows):
        row = table.add_row(); cells = row.cells
        for ci, val in enumerate(row_data):
            cells[ci].text = ''
            p = cells[ci].paragraphs[0]
            p.alignment = WD_ALIGN_PARAGRAPH.LEFT if ci == 0 else WD_ALIGN_PARAGRAPH.CENTER
            run = p.add_run(str(val))
            run.font.size = Pt(9); run.font.color.rgb = COLOR_BODY; run.font.name = 'Arial'
            if ri % 2 == 1: shade_cell(cells[ci], 'F0F7FC')
    if col_widths:
        for row in table.rows:
            for i, w in enumerate(col_widths):
                if i < len(row.cells): row.cells[i].width = Cm(w)
    return table

# Копируем таблицы из оригинала по индексу
def copy_table(src_idx):
    """Копирует таблицу из исходного документа."""
    from copy import deepcopy
    src_table = src_doc.tables[src_idx]
    new_table = doc.add_table(rows=len(src_table.rows), cols=len(src_table.columns))
    new_table.alignment = WD_TABLE_ALIGNMENT.CENTER
    for ri, src_row in enumerate(src_table.rows):
        for ci, src_cell in enumerate(src_row.cells):
            dst_cell = new_table.rows[ri].cells[ci]
            dst_cell.text = ''
            for p in src_cell.paragraphs:
                new_p = dst_cell.add_paragraph()
                for run in p.runs:
                    new_run = new_p.add_run(run.text)
                    new_run.font.size = Pt(9); new_run.font.color.rgb = COLOR_BODY; new_run.font.name = 'Arial'
                # Применяем shading заголовка
                if ri == 0:
                    shade_cell(dst_cell, '009FE3')
                    for r in new_p.runs:
                        r.font.bold = True; r.font.color.rgb = COLOR_WHITE
                elif ri % 2 == 1:
                    shade_cell(dst_cell, 'F0F7FC')
    return new_table

