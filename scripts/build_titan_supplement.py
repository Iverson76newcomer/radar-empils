# ---------- Утилиты ----------
def set_cell_bg(cell, color_hex):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement('w:shd')
    shd.set(qn('w:val'), 'clear')
    shd.set(qn('w:color'), 'auto')
    shd.set(qn('w:fill'), color_hex)
    tcPr.append(shd)

def set_cell_borders(cell, color='D0D0D0', sz='4'):
    tcPr = cell._tc.get_or_add_tcPr()
    tcBorders = OxmlElement('w:tcBorders')
    for edge in ('top', 'left', 'bottom', 'right'):
        el = OxmlElement(f'w:{edge}')
        el.set(qn('w:val'), 'single')
        el.set(qn('w:sz'), sz)
        el.set(qn('w:color'), color)
        tcBorders.append(el)
    tcPr.append(tcBorders)

def set_paragraph_spacing(p, before=0, after=6, line=1.3):
    pf = p.paragraph_format
    pf.space_before = Pt(before)
    pf.space_after = Pt(after)
    pf.line_spacing = line

def add_heading(text, level=1, color=DARK, size=None, before=12, after=8, orange_bar=False):
    p = doc.add_paragraph()
    set_paragraph_spacing(p, before=before, after=after, line=1.2)
    run = p.add_run(text)
    run.bold = True
    run.font.color.rgb = color
    if size is None:
        size = {1: 18, 2: 14, 3: 12}.get(level, 12)
    run.font.size = Pt(size)
    run.font.name = 'Arial'
    if orange_bar:
        # оранжевая вертикальная полоса слева
        pPr = p._p.get_or_add_pPr()
        pBdr = OxmlElement('w:pBdr')
        left = OxmlElement('w:left')
        left.set(qn('w:val'), 'single')
        left.set(qn('w:sz'), '24')
        left.set(qn('w:space'), '8')
        left.set(qn('w:color'), 'F47629')
        pBdr.append(left)
        pPr.append(pBdr)
        p.paragraph_format.left_indent = Cm(0.3)
    return p

def add_para(text, size=11, bold=False, color=None, italic=False, align='left', after=6, before=0):
    p = doc.add_paragraph()
    set_paragraph_spacing(p, before=before, after=after, line=1.3)
    if align == 'center':
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    elif align == 'right':
        p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    else:
        p.alignment = WD_ALIGN_PARAGRAPH.LEFT
    run = p.add_run(text)
    run.font.size = Pt(size)
    run.bold = bold
    run.italic = italic
    if color:
        run.font.color.rgb = color
    return p

def add_bullet(text, level=0, size=11, bold=False):
    p = doc.add_paragraph(style='List Bullet' if level == 0 else 'List Bullet 2')
    set_paragraph_spacing(p, before=0, after=3, line=1.25)
    p.paragraph_format.left_indent = Cm(0.6 + level * 0.5)
    run = p.runs[0] if p.runs else p.add_run()
    run.text = text
    run.font.size = Pt(size)
    run.font.name = 'Arial'
    if bold:
        run.bold = True
    return p

def add_callout(title, body, bg='FFF4ED', bar='F47629'):
    """Цветной блок-выноска с одинарной ячейкой."""
    tbl = doc.add_table(rows=1, cols=1)
    tbl.alignment = WD_TABLE_ALIGNMENT.CENTER
    tbl.autofit = False
    cell = tbl.cell(0, 0)
    cell.width = Cm(16.5)
    set_cell_bg(cell, bg)
    # левая граница — оранжевая (bar)
    tcPr = cell._tc.get_or_add_tcPr()
    tcBorders = OxmlElement('w:tcBorders')
    for edge, c in (('top', bg), ('right', bg), ('bottom', bg), ('left', bar)):
        el = OxmlElement(f'w:{edge}')
        el.set(qn('w:val'), 'single')
        el.set(qn('w:sz'), '36' if edge == 'left' else '4')
        el.set(qn('w:color'), c)
        tcBorders.append(el)
    tcPr.append(tcBorders)
    cell.vertical_alignment = WD_ALIGN_VERTICAL.CENTER

    # Заголовок callout
    if title:
        p = cell.paragraphs[0]
        set_paragraph_spacing(p, before=4, after=4, line=1.2)
        r = p.add_run(title)
        r.bold = True
        r.font.size = Pt(12)
        r.font.color.rgb = ORANGE
        r.font.name = 'Arial'
    # Тело
    if body:
        p2 = cell.add_paragraph()
        set_paragraph_spacing(p2, before=0, after=4, line=1.3)
        r2 = p2.add_run(body)
        r2.font.size = Pt(11)
        r2.font.color.rgb = DARK
        r2.font.name = 'Arial'
    # Поля ячейки
    tcPr = cell._tc.get_or_add_tcPr()
    tcMar = OxmlElement('w:tcMar')
    for edge, val in (('top', '120'), ('left', '200'), ('bottom', '120'), ('right', '200')):
        el = OxmlElement(f'w:{edge}')
        el.set(qn('w:w'), val)
        el.set(qn('w:type'), 'dxa')
        tcMar.append(el)
    tcPr.append(tcMar)
    # пустой абзац после таблицы
    add_para('', after=4, before=0)
    return tbl

def add_table(headers, rows, col_widths=None, header_bg='313131', header_color=WHITE,
              zebra=True, font_size=10):
    tbl = doc.add_table(rows=1 + len(rows), cols=len(headers))
    tbl.alignment = WD_TABLE_ALIGNMENT.CENTER
    tbl.autofit = False
    # ширина колонок
    if col_widths:
        for i, w in enumerate(col_widths):
            for cell in tbl.columns[i].cells:
                cell.width = Cm(w)
    # заголовок
    for i, h in enumerate(headers):
        c = tbl.rows[0].cells[i]
        set_cell_bg(c, header_bg)
        set_cell_borders(c, color='313131', sz='4')
        c.vertical_alignment = WD_ALIGN_VERTICAL.CENTER
        p = c.paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        set_paragraph_spacing(p, before=2, after=2, line=1.2)
        r = p.add_run(h)
        r.bold = True
        r.font.size = Pt(font_size)
        r.font.color.rgb = header_color
        r.font.name = 'Arial'
    # тело
    for ri, row in enumerate(rows):
        for ci, val in enumerate(row):
            c = tbl.rows[ri + 1].cells[ci]
            if zebra and ri % 2 == 1:
                set_cell_bg(c, 'F8F4F0')
            set_cell_borders(c, color='D0D0D0', sz='4')
            c.vertical_alignment = WD_ALIGN_VERTICAL.CENTER
            p = c.paragraphs[0]
            set_paragraph_spacing(p, before=2, after=2, line=1.25)
            r = p.add_run(str(val))
            r.font.size = Pt(font_size)
            r.font.name = 'Arial'
            # Выравнивание по типу контента
            if ci == 0:
                p.alignment = WD_ALIGN_PARAGRAPH.LEFT
                r.bold = True
                r.font.color.rgb = DARK
            elif isinstance(val, (int, float)) or (isinstance(val, str) and val.replace(' ', '').replace('₽', '').replace('%', '').replace(',', '.').replace('-', '').isdigit()):
                p.alignment = WD_ALIGN_PARAGRAPH.CENTER
                r.font.color.rgb = ORANGE
                r.bold = True
            else:
                p.alignment = WD_ALIGN_PARAGRAPH.LEFT
    add_para('', after=4, before=0)
    return tbl

def page_break():
    p = doc.add_paragraph()
    r = p.add_run()
    r.add_break(WD_BREAK.PAGE)

