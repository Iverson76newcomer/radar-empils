def add_h(text, level=1):
    h = doc.add_heading(text, level=level)
    for run in h.runs:
        run.font.color.rgb = RGBColor(0x1B, 0x2A, 0x4A)
    return h

def add_p(text, bold=False, italic=False, indent=False):
    p = doc.add_paragraph()
    if indent: p.paragraph_format.first_line_indent = Cm(1)
    run = p.add_run(text)
    run.bold = bold; run.italic = italic; run.font.size = Pt(11)
    return p

def add_b(text, level=0):
    p = doc.add_paragraph(text, style='List Bullet')
    p.paragraph_format.left_indent = Cm(1.5 + level * 1)
    return p

def add_tbl(headers, rows):
    table = doc.add_table(rows=1+len(rows), cols=len(headers))
    table.style = 'Light Grid Accent 1'
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, h in enumerate(headers):
        cell = table.rows[0].cells[i]; cell.text = h
        for p in cell.paragraphs:
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            for run in p.runs: run.bold = True; run.font.size = Pt(10)
    for ri, row_data in enumerate(rows):
        for ci, val in enumerate(row_data):
            cell = table.rows[ri+1].cells[ci]; cell.text = str(val)
            for p in cell.paragraphs:
                for run in p.runs: run.font.size = Pt(10)
    return table

