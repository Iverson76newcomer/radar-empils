def set_para(p, line_spacing=1.3, space_after=6, space_before=0, alignment=None):
    pf = p.paragraph_format
    pf.line_spacing = line_spacing
    pf.space_after = Pt(space_after)
    pf.space_before = Pt(space_before)
    if alignment is not None:
        p.alignment = alignment


def add_para(doc, text='', size=11, bold=False, color=DARK,
             alignment=WD_ALIGN_PARAGRAPH.LEFT, italic=False,
             line_spacing=1.3, space_after=6, space_before=0, font_name='Arial'):
    p = doc.add_paragraph()
    set_para(p, line_spacing=line_spacing, space_after=space_after,
             space_before=space_before, alignment=alignment)
    if text:
        run = p.add_run(text)
        run.font.size = Pt(size)
        run.font.bold = bold
        run.font.italic = italic
        run.font.color.rgb = color
        run.font.name = font_name
    return p


def add_divider(doc, color='C62828'):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(10)
    p.paragraph_format.space_after = Pt(10)
    pPr = p._element.get_or_add_pPr()
    pBdr = OxmlElement('w:pBdr')
    bottom = OxmlElement('w:bottom')
    bottom.set(qn('w:val'), 'single')
    bottom.set(qn('w:sz'), '12')
    bottom.set(qn('w:space'), '1')
    bottom.set(qn('w:color'), color)
    pBdr.append(bottom)
    pPr.append(pBdr)


def add_section_label(doc, text, color=RED):
    p = doc.add_paragraph()
    set_para(p, line_spacing=1.2, space_after=4, space_before=10)
    run = p.add_run(text)
    run.font.size = Pt(12)
    run.font.bold = True
    run.font.color.rgb = color
    run.font.name = 'Arial'
    rPr = run._element.get_or_add_rPr()
    caps = OxmlElement('w:caps')
    caps.set(qn('w:val'), 'true')
    rPr.append(caps)


def add_styled_table(doc, headers, rows, col_widths=None):
    table = doc.add_table(rows=1 + len(rows), cols=len(headers))
    table.style = 'Table Grid'
    
    for ci, h in enumerate(headers):
        cell = table.cell(0, ci)
        cell.text = ''
        p = cell.paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        run = p.add_run(h)
        run.font.size = Pt(10)
        run.font.bold = True
        run.font.color.rgb = WHITE
        run.font.name = 'Arial'
        shading = OxmlElement('w:shd')
        shading.set(qn('w:val'), 'clear')
        shading.set(qn('w:fill'), '1E3A5F')
        cell._element.get_or_add_tcPr().append(shading)
    
    for ri, row in enumerate(rows):
        for ci, val in enumerate(row):
            cell = table.cell(ri + 1, ci)
            cell.text = ''
            p = cell.paragraphs[0]
            p.alignment = WD_ALIGN_PARAGRAPH.LEFT
            run = p.add_run(str(val))
            run.font.size = Pt(10)
            run.font.name = 'Arial'
            run.font.color.rgb = DARK
            if ci == 0:
                run.font.bold = True
    
    if col_widths:
        for ci, w in enumerate(col_widths):
            for cell in table.columns[ci].cells:
                cell.width = Cm(w)
    
    return table


