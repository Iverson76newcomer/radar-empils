from docx import Document

# ============================================================
# Файл 2 — Titan_economic_calculation.docx
# ============================================================
OUT2 = '/home/z/my-project/download/Titan_economic_calculation.docx'
doc2 = Document(OUT2)

# Заменяем финал предложения с добавлением новой фразы
old2 = ('остальное — работа, расход материалов, количество перекрасок за срок службы.')
new2 = ('остальное — работа, расход материалов, количество перекрасок за срок службы, '
        'а также декоративный и визуальный эффект: TITAN образует высокоглянцевое '
        'ровное покрытие с насыщенным цветом по каталогу RAL, в то время как ПФ-115 '
        'дает матовый «технический» вид, который не подходит для лицевых поверхностей '
        '(ворот, дверей, заборов) и быстро выцветает под УФ.')

def replace_text_in_element(elem, old, new):
    ns = {'w': 'http://schemas.openxmlformats.org/wordprocessingml/2006/main'}
    t_nodes = elem.findall('.//w:t', ns)
    if not t_nodes:
        return 0
    full_text = ''.join(t.text or '' for t in t_nodes)
    if old not in full_text:
        return 0
    new_text = full_text.replace(old, new)
    if t_nodes:
        t_nodes[0].text = new_text
        for t in t_nodes[1:]:
            t.text = ''
    return 1

c2 = 0
for p in doc2.paragraphs:
    c2 += replace_text_in_element(p._p, old2, new2)
    if c2:
        break

print(f'Файл 2: замен: {c2}')
doc2.save(OUT2)

