# ---------- Заполнение строк ----------
thin_border = Side(style='thin', color='D0D0D0')
border_all = Border(left=thin_border, right=thin_border, top=thin_border, bottom=thin_border)

start_row = 5
for i, c in enumerate(companies, start=1):
    row = start_row + i - 1
    values = [i, c['name'], c['activity'], c['coop'], c['phone'], c['email'], c['website']]

    # Zebra
    bg = ZEBRA if i % 2 == 0 else WHITE

    for col_idx, val in enumerate(values, start=1):
        cell = ws.cell(row=row, column=col_idx, value=val)
        cell.font = Font(name='Arial', size=10)
        cell.fill = PatternFill('solid', fgColor=bg)
        cell.alignment = Alignment(horizontal='left', vertical='top', wrap_text=True)
        cell.border = border_all

        # Жирное оранжевое название компании
        if col_idx == 2:
            cell.font = Font(name='Arial', size=11, bold=True, color=ORANGE)
        # Номер по центру
        if col_idx == 1:
            cell.alignment = Alignment(horizontal='center', vertical='center')
            cell.font = Font(name='Arial', size=11, bold=True, color=ORANGE)

    # Высота строки — зависит от объёма описания кооперации
    desc_lines = c['coop'].count('\n') + 1
    activity_lines = max(2, len(c['activity']) // 60 + 1)
    row_height = max(80, max(desc_lines, activity_lines) * 15 + 20)
    ws.row_dimensions[row].height = row_height

# ---------- Ширина колонок ----------
