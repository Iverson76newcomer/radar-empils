# Цвета для новых стран (светлые, чтобы отличались от старых)
COUNTRY_COLORS = {
    "ОАЭ":           "FFE082",  # тёплый жёлто-оранжевый
    "Туркменистан":  "B0BEC5",  # сине-серый (закрытая экономика)
    "Таджикистан":   "A5D6A7",  # светло-зелёный (высокий потенциал)
}

# Цвета для выводов
CONCLUSION_COLORS = {
    "ОАЭ":           "FFE0B2",   # оранжевый — приоритет 4
    "Туркменистан":  "E0E0E0",   # серый — рисковый
    "Таджикистан":   "C8E6C9",   # зелёный — приоритет 2-3
}

CONCLUSION_FONTS = {
    "ОАЭ":           Font(name="Calibri", size=11, color="E65100", bold=True),
    "Туркменистан":  Font(name="Calibri", size=11, color="616161", italic=True),
    "Таджикистан":   Font(name="Calibri", size=11, color="1B5E20", bold=True),
}

# Маппинг строк
ROW_MAP = {
    "Население":            5,
    "Производство":         6,
    "Потребление":          7,
    "Соотношение":          8,
    "Экспорт":              9,
    "Место":                10,
    "Особенности":          11,
    "Разбивка":             12,
    "Рост":                 13,
    "Соотношение_экс_имп":  14,
    "Вывод":                15,
}

# Заполняем
for country, info in DATA.items():
    col = info["col"]
    color = COUNTRY_COLORS[country]

    for criterion, value in info.items():
        if criterion == "col":
            continue
        row = ROW_MAP[criterion]
        cell = ws.cell(row=row, column=col, value=value)

        if criterion == "Вывод":
            # Специальный цвет и шрифт для вывода
            cell.font = CONCLUSION_FONTS[country]
            cell.fill = PatternFill("solid", fgColor=CONCLUSION_COLORS[country])
        else:
            cell.font = font_val
            cell.fill = PatternFill("solid", fgColor=color)

        cell.alignment = Alignment(horizontal="left", vertical="top", wrap_text=True)
        cell.border = thin_border

# Сохраним
wb.save(DST)

