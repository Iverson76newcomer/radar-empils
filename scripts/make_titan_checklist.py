# Условное форматирование для колонки "Статус"
def add_status_formatting(ws, col_letter, start_row, end_row):
    """Добавляет условное форматирование для колонки статуса."""
    green_fill = PatternFill("solid", fgColor=GREEN)
    yellow_fill = PatternFill("solid", fgColor=YELLOW)
    red_fill = PatternFill("solid", fgColor=RED)
    gray_fill = PatternFill("solid", fgColor=GRAY)

    rng = f"{col_letter}{start_row}:{col_letter}{end_row}"
    ws.conditional_formatting.add(rng, CellIsRule(operator="equal", formula=['"Выполнено"'], fill=green_fill))
    ws.conditional_formatting.add(rng, CellIsRule(operator="equal", formula=['"В работе"'], fill=yellow_fill))
    ws.conditional_formatting.add(rng, CellIsRule(operator="equal", formula=['"Не начато"'], fill=red_fill))
    ws.conditional_formatting.add(rng, CellIsRule(operator="equal", formula=['"Не требуется"'], fill=gray_fill))
    ws.conditional_formatting.add(rng, CellIsRule(operator="equal", formula=['"Частично"'], fill=yellow_fill))

# Заголовок листа
def write_header(ws, title, subtitle):
    ws.merge_cells("A1:H1")
    ws["A1"] = title
    ws["A1"].font = Font(name="Calibri", size=16, bold=True, color=WHITE)
    ws["A1"].fill = PatternFill("solid", fgColor=ORANGE)
    ws["A1"].alignment = Alignment(horizontal="center", vertical="center")
    ws.row_dimensions[1].height = 36

    ws.merge_cells("A2:H2")
    ws["A2"] = subtitle
    ws["A2"].font = Font(name="Calibri", size=10, italic=True, color=DARK)
    ws["A2"].fill = PatternFill("solid", fgColor=LIGHT_ORANGE)
    ws["A2"].alignment = Alignment(horizontal="center", vertical="center")
    ws.row_dimensions[2].height = 22

# Заголовки таблицы
def write_table_header(ws, row=4):
    headers = ["№", "Этап / Направление", "Задача", "Источник (слайд)", "Срок", "Ответственный", "Статус", "Комментарий"]
    for col, h in enumerate(headers, 1):
        cell = ws.cell(row=row, column=col, value=h)
        cell.font = Font(name="Calibri", size=11, bold=True, color=WHITE)
        cell.fill = PatternFill("solid", fgColor=DARK)
        cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        cell.border = thin
    ws.row_dimensions[row].height = 32

# Запись строк
def write_rows(ws, start_row, data):
    for idx, row_data in enumerate(data):
        r = start_row + idx
        for col, val in enumerate(row_data, 1):
            cell = ws.cell(row=r, column=col, value=val)
            cell.font = Font(name="Calibri", size=10, color=DARK,
                             bold=(col == 1 or col == 2))
            cell.alignment = Alignment(
                horizontal="center" if col in (1, 4, 5, 7) else "left",
                vertical="center", wrap_text=True)
            cell.border = thin
            # Подсветка по этапам
            stage = str(row_data[1]) if row_data[1] else ""
            if "ЭТАП 0" in stage:
                cell.fill = PatternFill("solid", fgColor="E3F2FD")
            elif "ЭТАП 1" in stage:
                cell.fill = PatternFill("solid", fgColor="FFF9C4")
            elif "ЭТАП 2" in stage:
                cell.fill = PatternFill("solid", fgColor="FFE0B2")
            elif "KPI" in stage:
                cell.fill = PatternFill("solid", fgColor="F8BBD0")
            elif "ПЛАН" in stage:
                cell.fill = PatternFill("solid", fgColor="FFCDD2")
            elif "ОБУЧЕНИЕ" in stage:
                cell.fill = PatternFill("solid", fgColor="E8F5E9")
            elif "MML" in stage:
                cell.fill = PatternFill("solid", fgColor="F3E5F5")
            elif "ПИЛОТ" in stage:
                cell.fill = PatternFill("solid", fgColor=LIGHT_ORANGE)
            else:
                if idx % 2 == 0:
                    cell.fill = PatternFill("solid", fgColor="FAFAFA")
        ws.row_dimensions[r].height = 45

    # Условное форматирование для колонки "Статус" (G)
    add_status_formatting(ws, "G", start_row, start_row + len(data) - 1)

    # Установка ширины колонок
    widths = [5, 22, 45, 12, 16, 18, 14, 30]
    for i, w in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(i)].width = w

# Дропдаун для колонки "Статус"
def add_status_dropdown(ws, start_row, end_row):
    from openpyxl.worksheet.datavalidation import DataValidation
    dv = DataValidation(type="list", formula1='"Выполнено,В работе,Не начато,Частично,Не требуется"', allow_blank=True)
    dv.add(f"G{start_row}:G{end_row}")
    ws.add_data_validation(dv)

