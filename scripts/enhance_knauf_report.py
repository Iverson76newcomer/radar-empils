COLOR_PRIMARY = RGBColor(0x0B, 0x1C, 0x2C)
COLOR_ACCENT = RGBColor(0x00, 0x9F, 0xE3)
COLOR_BODY = RGBColor(0x1A, 0x2B, 0x3D)
COLOR_WHITE = RGBColor(0xFF, 0xFF, 0xFF)
COLOR_GREEN = RGBColor(0x16, 0xA3, 0x4A)
COLOR_RED = RGBColor(0xC0, 0x39, 0x2B)
COLOR_YELLOW = RGBColor(0xD9, 0x77, 0x06)

def shade_cell(cell, hex_color):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement('w:shd')
    shd.set(qn('w:val'), 'clear')
    shd.set(qn('w:color'), 'auto')
    shd.set(qn('w:fill'), hex_color)
    tcPr.append(shd)

def h1(text):
    p = doc.add_paragraph()
    run = p.add_run(text)
    run.font.size = Pt(16)
    run.font.bold = True
    run.font.color.rgb = COLOR_PRIMARY
    run.font.name = 'Arial'
    return p

def h2(text):
    p = doc.add_paragraph()
    run = p.add_run(text)
    run.font.size = Pt(13)
    run.font.bold = True
    run.font.color.rgb = COLOR_PRIMARY
    run.font.name = 'Arial'
    return p

def h3(text):
    p = doc.add_paragraph()
    run = p.add_run(text)
    run.font.size = Pt(11)
    run.font.bold = True
    run.font.color.rgb = COLOR_ACCENT
    run.font.name = 'Arial'
    return p

def body(text):
    p = doc.add_paragraph()
    p.paragraph_format.first_line_indent = Cm(0.5)
    p.paragraph_format.line_spacing = 1.3
    p.paragraph_format.space_after = Pt(6)
    run = p.add_run(text)
    run.font.size = Pt(10)
    run.font.color.rgb = COLOR_BODY
    run.font.name = 'Arial'
    return p

def bullet(text):
    p = doc.add_paragraph()
    p.paragraph_format.left_indent = Cm(0.8)
    p.paragraph_format.space_after = Pt(3)
    run = p.add_run('▸ ' + text)
    run.font.size = Pt(10)
    run.font.color.rgb = COLOR_BODY
    run.font.name = 'Arial'
    return p

def make_table(headers, rows, col_widths=None):
    table = doc.add_table(rows=1, cols=len(headers))
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    hdr = table.rows[0].cells
    for i, h in enumerate(headers):
        hdr[i].text = ''
        p = hdr[i].paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        run = p.add_run(h)
        run.font.bold = True
        run.font.size = Pt(9)
        run.font.color.rgb = COLOR_WHITE
        run.font.name = 'Arial'
        shade_cell(hdr[i], '009FE3')
    for ri, row_data in enumerate(rows):
        row = table.add_row()
        cells = row.cells
        for ci, val in enumerate(row_data):
            cells[ci].text = ''
            p = cells[ci].paragraphs[0]
            p.alignment = WD_ALIGN_PARAGRAPH.LEFT if ci == 0 else WD_ALIGN_PARAGRAPH.CENTER
            run = p.add_run(str(val))
            run.font.size = Pt(9)
            run.font.color.rgb = COLOR_BODY
            run.font.name = 'Arial'
            if ri % 2 == 1:
                shade_cell(cells[ci], 'F0F7FC')
    if col_widths:
        for row in table.rows:
            for i, w in enumerate(col_widths):
                if i < len(row.cells):
                    row.cells[i].width = Cm(w)
    return table

