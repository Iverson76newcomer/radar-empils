def get_region_from_inn(inn):
    """Определить регион по первым 2 цифрам ИНН"""
    inn_str = str(inn).strip()
    if len(inn_str) >= 2:
        region_code = inn_str[:2]
        return INN_REGION.get(region_code)
    return None

def get_federal_district(city):
    """Определить федеральный округ по городу"""
    if not city:
        return None
    city_lower = city.strip().lower()
    for key, fo in CITY_TO_FO.items():
        if key in city_lower:
            return fo
    return None

