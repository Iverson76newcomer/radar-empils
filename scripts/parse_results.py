def extract_address_from_text(text):
    """Извлечь почтовый адрес из текста"""
    if not text:
        return None
    
    # Ищем паттерн с индексом
    patterns = [
        r'(\d{6},?\s*[^<]*?г\.[^<]*?(?:,?\s*[^<]*?){0,5})',
        r'(?:адрес[у:]?\s*:?\s*)(.{20,250})',
        r'(?:Юр\.?\s*адрес[у:]?\s*:?\s*)(.{20,250})',
        r'(?:Юридический\s+адрес[у:]?\s*:?\s*)(.{20,250})',
    ]
    
    for p in patterns:
        m = re.search(p, text, re.IGNORECASE)
        if m:
            addr = m.group(1).strip()
            addr = re.sub(r'\s+', ' ', addr)
            addr = addr.rstrip('.,; ')
            if len(addr) > 10 and 'г.' in addr or len(addr) > 20:
                return addr[:200]
    
    return None

def extract_email_from_text(text):
    """Извлечь email из текста"""
    if not text:
        return None
    pattern = r'[\w\.-]+@[\w\.-]+\.\w{2,10}'
    matches = re.findall(pattern, text)
    for email in matches:
        lower = email.lower()
        if any(skip in lower for skip in ['example', 'test', 'email]', 'yoursite', 'domain', 'sentry', 'wixpress', 'gravatar']):
            continue
        return email
    return matches[0] if matches else None

def extract_website_from_results(results, company_name):
    """Извлечь сайт компании из результатов поиска"""
    if not results:
        return None
    
    skip_domains = [
        'rusprofile.ru', 'list-org.com', 'spark-interfax.ru',
        'companies.rbc.ru', 'zachestnyibiznes.ru', 'sbis.ru',
        'org-info.com', 'find-org.com', 'orglist.ru', 'regfile.ru',
        'ruscompany.com', 'inc-legal.ru', 'buhschetchet.ru',
        'taxcom.ru', 'kontragent.skbkontur.ru', 'focus.kontur.ru',
        'glayl.com', 'nalog.gov.ru', 'egrul.ru', 'egrul.nalog.ru',
        'google.com', 'yandex.ru', '2gis.ru', 'avito.ru',
        'venyoo.ru', 'ul.company', 'spark', 'interfax',
        'company-profile', 'company-info', 'open-broker',
    ]
    
    for r in results:
        url = r.get('url', '')
        host = r.get('host_name', '')
        
        if any(d in host for d in skip_domains):
            continue
        
        if url.startswith('http'):
            domain_match = re.match(r'https?://(?:www\.)?([^/]+)', url)
            if domain_match:
                domain = domain_match.group(1)
                if not any(d in domain for d in ['google', 'yandex', 'bing', '2gis', 'avito', 'rusprofile', 'list-org']):
                    return f"https://{domain}"
    
    return None

def load_search_results(inn):
    """Загрузить результаты поиска для ИНН"""
    # Пробуем оба варианта имени файла
    for fname in [f'{inn}.json', f'inn_{inn}.json']:
        fpath = os.path.join(SEARCH_DIR, fname)
        if os.path.exists(fpath) and os.path.getsize(fpath) > 100:
            try:
                with open(fpath, 'r') as f:
                    data = json.load(f)
                if isinstance(data, list) and len(data) > 0:
                    return data
            except:
                pass
    return None

